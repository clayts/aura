local c = require("aura").colors

-- Mixes fg over bg, alpha of the way, as Zed draws a translucent colour
local function blend(fg, bg, alpha)
	local function channel(color, i)
		return tonumber(color:sub(i, i + 1), 16)
	end
	local out = "#"
	for _, i in ipairs({ 2, 4, 6 }) do
		out = out .. string.format("%02x", math.floor(alpha * channel(fg, i) + (1 - alpha) * channel(bg, i) + 0.5))
	end
	return out
end
local function tint(color, alpha)
	return blend(color, c.grey0, alpha)
end

